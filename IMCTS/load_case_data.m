function [data, ref] = load_case_data(source)
% Exact orbital data from Ye et al. (2025), Tables 7 and 8.
% Columns: [height_km, e, i_deg, RAAN_deg, argp_deg, M_deg]

if nargin < 1 || isempty(source)
    source = 'paper';
end

switch lower(source)
    case 'paper'
        [data, ref] = load_from_paper();
    case 'pmdt'
        [data, ref] = load_from_pmdt();
    otherwise
        error('Unknown source "%s". Use paper or pmdt.', source);
end
end

