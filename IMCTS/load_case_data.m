function [data, ref] = load_from_pmdt()
S = load('DebrisData.mat', 'DebrisData');
D = S.DebrisData;
n = numel(D);

Re = 6378.137; % km
targets = zeros(n, 6);
for i = 1:n
    k = D(i).Kepl(:);
    a_km = k(1) / 1e3;
    targets(i, 1) = a_km - Re;      % height_km
    targets(i, 2) = k(2);           % e
    targets(i, 3) = rad2deg(k(3));  % i_deg
    targets(i, 4) = rad2deg(k(4));  % RAAN_deg
    targets(i, 5) = rad2deg(k(5));  % argp_deg
    targets(i, 6) = rad2deg(k(6));  % M_deg
end

data.targetIds = (1:n)';
data.targets = targets;
data.targetNames = string({D.name})';
data.targetMassKg = [D.mass]';

% Keep same spacecraft initial states used by IMCTS reproduction.
data.sscIds = (1:2)';
data.ssc = [
796.46 0.0089 98.749 18.725 73.871 14.883
787.87 0.0041 96.345 30.598 207.234 80.230
];

ref = struct();
end
